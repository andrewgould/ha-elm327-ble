"""Regenerate custom_components/elm327_ble/vehicles.py from OBDb.

Lists the OBDb organisation's car repositories, downloads each signal set and
keeps the cars with at least one reading this integration can use. Run before a
release so the options list picks up new cars:

    python scripts/update_vehicles.py [cache dir]

Needs the GitHub CLI (gh), signed in, for the repository listing.
"""

import collections
import importlib.util
import json
import pathlib
import subprocess
import sys
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor

ROOT = pathlib.Path(__file__).parents[1]
COMPONENT = ROOT / "custom_components/elm327_ble"

spec = importlib.util.spec_from_file_location("obdb", COMPONENT / "obdb.py")
obdb = importlib.util.module_from_spec(spec)
sys.modules["obdb"] = obdb
spec.loader.exec_module(obdb)


def repos() -> list[str]:
    out = subprocess.run(["gh", "api", "--paginate", "orgs/OBDb/repos?per_page=100",
                          "--jq", ".[] | select(.archived | not) | .name"],
                         check=True, capture_output=True, text=True).stdout
    # Car repositories are Make-Model; the rest are makes, tools and templates.
    return sorted(n for n in out.split() if "-" in n and not n.startswith(".")
                  and not n.endswith(".community") and n != "vscode-obdb")


def fetch(repo: str, cache: pathlib.Path) -> dict | None:
    path = cache / f"{repo}.json"
    if not path.exists():
        try:
            with urllib.request.urlopen(obdb.URL.format(repo), timeout=30) as response:
                path.write_bytes(response.read())
        except urllib.error.HTTPError:
            return None
    try:
        return json.loads(path.read_bytes())
    except ValueError:
        return None


def main() -> None:
    cache = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/obdb")
    cache.mkdir(parents=True, exist_ok=True)
    names = repos()
    with ThreadPoolExecutor(16) as pool:
        signalsets = dict(zip(names, pool.map(lambda r: fetch(r, cache), names), strict=True))

    usable, coverage = [], collections.Counter()
    for repo, signalset in signalsets.items():
        found = obdb.keys(obdb.select(signalset or {}, None))
        if found:
            usable.append(repo)
            coverage.update(found)
    lines = [
        '"""Cars OBDb has readings for that this integration can use.',
        "",
        "Generated by scripts/update_vehicles.py; don't edit by hand.",
        '"""',
        "",
        "VEHICLES = (",
        *(f'    "{repo}",' for repo in usable),
        ")",
        "",
    ]
    (COMPONENT / "vehicles.py").write_text("\n".join(lines))
    print(f"{len(usable)} of {len(names)} cars have usable readings")
    for key, count in coverage.most_common():
        print(f"  {count:4} {key}")


if __name__ == "__main__":
    main()
